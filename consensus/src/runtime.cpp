#include "runtime.hpp"
#include "simulator.hpp"
#include "support.hpp"

namespace lab {
int Runtime::node_id() const {
    return node;
}
int Runtime::node_count() const {
    return static_cast<int>(engine.nodes.size());
}
Node& Runtime::application() {
    return engine.nodes.at(node);
}
std::mt19937_64& Runtime::random() {
    return engine.random;
}
void Runtime::send(Message message) {
    // A protocol may send from itself only. It cannot impersonate a peer.
    require(message.kind != "response", "Client responses are generated by the application.");
    require(message.to >= 0 && message.to < node_count(), "Destination outside cluster.");
    message.from = node;
    engine.send(std::move(message));
}
void Runtime::schedule(const std::string& tag, int milliseconds, int generation) {
    engine.schedule(node, tag, milliseconds, generation);
}
void Runtime::learn(int slot, const Command& command) {
    require(engine.protocols[node]->uses_ordered_log(),
            "Async protocols do not emit log decisions.");
    engine.learn(node, slot, command);
}
void Runtime::complete_locally(const Command& command, const std::string& result) {
    require(!engine.protocols[node]->uses_ordered_log(),
            "Ordered operations complete through log application.");
    engine.record_local_result(node, command, result);
}
void Runtime::say(const std::string& explanation) {
    engine.say(explanation);
}
} // namespace lab
